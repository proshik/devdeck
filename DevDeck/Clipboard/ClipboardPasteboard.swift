import AppKit

struct ClipboardSnapshot: Sendable {
    var text: String?
    var imageData: Data?
    var imageType: String?
    var fileURLs: [URL] = []
    var sourceBundleID: String?
    var sourceName: String?
    var types: Set<String> = []
    var activeBundleID: String?
    var isEligible: Bool {
        types.isDisjoint(with: Self.ignoredTypes) && (!types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) || !fileURLs.isEmpty)
    }
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
        "com.agilebits.onepassword"
    ]
}

enum ClipboardAccess: Equatable { case allowed, needsPermission, denied }

@MainActor protocol ClipboardPasteboard {
    var changeCount: Int { get }
    var access: ClipboardAccess { get }
    func snapshot(excludedBundleIDs: Set<String>) -> ClipboardSnapshot?
    func write(_ entry: ClipboardEntry) -> Int?
    func requestAccess()
}

@MainActor final class SystemClipboardPasteboard: ClipboardPasteboard {
    private let pasteboard: NSPasteboard
    private let files: any ClipboardFileChecking
    init(pasteboard: NSPasteboard = .general, files: any ClipboardFileChecking = ClipboardFileAvailability()) {
        self.pasteboard = pasteboard; self.files = files
    }
    var changeCount: Int { pasteboard.changeCount }
    var access: ClipboardAccess {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: return .allowed
            case .alwaysDeny: return .denied
            case .default, .ask: return .needsPermission
            @unknown default: return .needsPermission
            }
        }
        return .allowed
    }
    func requestAccess() { _ = pasteboard.string(forType: .string) }
    func snapshot(excludedBundleIDs: Set<String>) -> ClipboardSnapshot? {
        // Foreground app is only a conservative exclusion, never attributed as source.
        let active = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard active.map({ !excludedBundleIDs.contains($0) }) ?? true else { return nil }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ClipboardSnapshot.ignoredTypes) else { return nil }
        let source = pasteboard.string(forType: .init("org.nspasteboard.source")).flatMap { $0.isEmpty ? nil : $0 }
        guard source.map({ !excludedBundleIDs.contains($0) }) ?? true else { return nil }
        let sourceName = source.flatMap { NSWorkspace.shared.urlForApplication(withBundleIdentifier: $0) }
            .map { FileManager.default.displayName(atPath: $0.path).replacingOccurrences(of: ".app", with: "") }
        var result = ClipboardSnapshot(text: nil, sourceBundleID: source, sourceName: sourceName, types: types, activeBundleID: active)
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            result.fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: { types.contains($0.rawValue) }) {
            result.imageType = type.rawValue; result.imageData = pasteboard.data(forType: type)
        } else { result.text = pasteboard.string(forType: .string) }
        return result
    }
    func write(_ entry: ClipboardEntry) -> Int? {
        guard entry.content.isValid else { return nil }
        let items: [NSPasteboardItem]
        switch entry.content {
        case .text(let text):
            let item = NSPasteboardItem()
            guard item.setString(text, forType: .string) else { return nil }
            items = [item]
        case .image(let image):
            let item = NSPasteboardItem()
            guard item.setData(image.data, forType: .init(image.type)) else { return nil }
            items = [item]
        case .files(let urls):
            guard urls.allSatisfy({ files.isAvailable($0) }) else { return nil }
            var prepared: [NSPasteboardItem] = []
            for url in urls {
                let item = NSPasteboardItem()
                guard item.setString(url.absoluteString, forType: .fileURL) else { return nil }
                prepared.append(item)
            }
            items = prepared
        }
        for item in items {
            guard item.setString(entry.sourceBundleID ?? "", forType: .init("org.nspasteboard.source")) else { return nil }
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects(items) ? pasteboard.changeCount : nil
    }
}
